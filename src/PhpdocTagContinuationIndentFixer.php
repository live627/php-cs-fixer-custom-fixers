<?php

declare(strict_types=1);

namespace Live627\PhpCsFixer\CustomFixers;

use PhpCsFixer\AbstractFixer;
use PhpCsFixer\Fixer\ConfigurableFixerInterface;
use PhpCsFixer\Fixer\ConfigurableFixerTrait;
use PhpCsFixer\FixerConfiguration\FixerConfigurationResolver;
use PhpCsFixer\FixerConfiguration\FixerConfigurationResolverInterface;
use PhpCsFixer\FixerConfiguration\FixerOptionBuilder;
use PhpCsFixer\FixerDefinition\CodeSample;
use PhpCsFixer\FixerDefinition\FixerDefinition;
use PhpCsFixer\FixerDefinition\FixerDefinitionInterface;
use PhpCsFixer\Tokenizer\Token;
use PhpCsFixer\Tokenizer\Tokens;

/**
 * Enforces consistent indentation of PHPDoc tag continuation lines.
 *
 * Nonempty continuation lines are indented by the configured number of spaces,
 * plus their existing indentation relative to the least-indented continuation
 * line belonging to the same tag. This preserves relative indentation in
 * constructs such as nested lists, code examples, and array shapes.
 *
 * Configuration options:
 *
 * - `indent`: Number of spaces to use for the least-indented continuation line.
 * - `exclude`: Exact PHPDoc tag names to skip, without the leading `@`.
 * - `exclude_patterns`: Regular expressions matching PHPDoc tag names to skip.
 *
 * Example:
 *
 * ```php
 * [
 *     'indent' => 3,
 *     'exclude' => ['param', 'return'],
 *     'exclude_patterns' => ['/^phpstan-/'],
 * ]
 * ```
 *
 * @phpstan-type _AutogeneratedInputConfiguration array{
 *     indent?: int,
 *     exclude?: list<string>,
 *     exclude_patterns?: list<string>,
 * }
 * @phpstan-type _AutogeneratedComputedConfiguration array{
 *     indent: int,
 *     exclude: list<string>,
 *     exclude_patterns: list<string>,
 * }
 *
 * @implements ConfigurableFixerInterface<_AutogeneratedInputConfiguration, _AutogeneratedComputedConfiguration>
 *
 * @no-named-arguments Parameter names are not covered by the backward compatibility promise.
 */
final class PhpdocTagContinuationIndentFixer extends AbstractFixer implements ConfigurableFixerInterface
{
	/** @use ConfigurableFixerTrait<_AutogeneratedInputConfiguration, _AutogeneratedComputedConfiguration> */
	use ConfigurableFixerTrait;

	/*********************
	 * Internal properties
	 *********************/

	/** Compiled exclusion matcher. */
	private string $exclude_pattern = '';

	/****************
	 * Public methods
	 ****************/

	public function getName(): string
	{
		return 'Live627/' . parent::getName();
	}

	public function getDefinition(): FixerDefinitionInterface
	{
		$code = <<<'PHP'
			<?php

			/**
			 * @param string $name Description.
			 * Continuation of the description.
			 *   Another continuation.
			 */

			PHP;

		return new FixerDefinition(
			'Continuation lines of PHPDoc tags must use the configured indentation.',
			[
				new CodeSample($code),
				new CodeSample($code, ['indent' => 4]),
				new CodeSample($code, ['exclude' => ['return']]),
				new CodeSample($code, ['exclude_patterns' => ['/^phpstan-/']]),
			],
			'Nonempty continuation lines are indented by the configured number of spaces, plus their existing indentation relative to the least-indented continuation line belonging to the same tag. This preserves relative indentation in constructs such as nested lists, code examples, and array shapes.',
		);
	}

	/**
	 * {@inheritdoc}
	 *
	 * Must run after PhpdocAlignFixer.
	 */
	public function getPriority(): int
	{
		return -43;
	}

	public function isCandidate(Tokens $tokens): bool
	{
		return $tokens->isTokenKindFound(\T_DOC_COMMENT);
	}

	/******************
	 * Internal methods
	 ******************/

	protected function applyFix(\SplFileInfo $file, Tokens $tokens): void
	{
		foreach ($tokens as $index => $token) {
			if (!$token->isGivenKind(\T_DOC_COMMENT)) {
				continue;
			}

			$content = $token->getContent();
			$new_content = $this->fixDocBlock($content);

			if ($new_content !== $content) {
				$tokens[$index] = new Token([\T_DOC_COMMENT, $new_content]);
			}
		}
	}

	protected function createConfigurationDefinition(): FixerConfigurationResolverInterface
	{
		$indent = new FixerOptionBuilder(
			'indent',
			'Number of spaces following the standard PHPDoc prefix (` * `) on continuation lines.',
		);

		$indent
			->setAllowedTypes(['int'])
			->setAllowedValues([static fn(int $value): bool => $value >= 0])
			->setDefault(3);

		$exclude = new FixerOptionBuilder(
			'exclude',
			'PHPDoc tag names to exclude, without the leading `@`.',
		);

		$exclude
			->setAllowedTypes(['array'])
			->setDefault([]);

		$exclude_patterns = new FixerOptionBuilder(
			'exclude_patterns',
			'Regular expressions matching PHPDoc tag names to exclude.',
		);

		$exclude_patterns
			->setAllowedTypes(['array'])
			->setDefault([]);

		return new FixerConfigurationResolver([
			$indent->getOption(),
			$exclude->getOption(),
			$exclude_patterns->getOption(),
		]);
	}

	protected function configurePostNormalisation(): void
	{
		$patterns = [];

		// Reset state.
		$this->exclude_pattern = '';

		foreach ($this->configuration['exclude'] as $name) {
			$patterns[] = preg_quote($name, '~');
		}

		if ($patterns !== []) {
			$this->exclude_pattern = '~^(?:' . implode('|', $patterns) . ')$';
		}

		$patterns = [];

		foreach ($this->configuration['exclude_patterns'] as $pattern) {
			$patterns[] = trim($pattern, '/');
		}

		if ($patterns !== []) {
			$this->exclude_pattern .= ($this->exclude_pattern !== '' ? '|' : '~') . implode('|', $patterns);
		}

		if ($this->exclude_pattern !== '' && $this->exclude_pattern[-1] !== '~') {
			$this->exclude_pattern .= '~';
		}
	}

	/**
	 * Normalizes continuation indentation while preserving relative indentation.
	 */
	private function fixDocBlock(string $content): string
	{
		$indent = $this->configuration['indent'];
		$replacements = [];

		preg_match_all(
			'~^[ \t]*\*[ \t]*@(?P<name>[a-zA-Z0-9_\\\\-]+)(?P<value>.*?)(?=^[ \t]*\*[ \t]*@|^[ \t]*\*/|\z)~ms',
			$content,
			$tags,
			PREG_SET_ORDER | PREG_OFFSET_CAPTURE,
		);

		foreach ($tags as $tag) {
			$tag_name = $tag['name'][0];

			if ($this->exclude_pattern !== '' && preg_match($this->exclude_pattern, $tag_name)) {
				continue;
			}

			$value = $tag['value'][0];
			$value_offset = $tag['value'][1];

			preg_match_all(
				'~(?:\r\n|\n|\r)[ \t]*\* (?<spacing>[ \t]*)(?<text>\S[^\r\n]*)~',
				$value,
				$continuations,
				PREG_SET_ORDER | PREG_OFFSET_CAPTURE,
			);

			$min_indent = null;

			foreach ($continuations as $continuation) {
				$line_indent = \strlen($continuation['spacing'][0]);

				$min_indent = $min_indent === null
					? $line_indent
					: min($min_indent, $line_indent);
			}

			if ($min_indent === null) {
				continue;
			}

			foreach ($continuations as $continuation) {
				$line_indent = \strlen($continuation['spacing'][0]);

				$replacements[] = [
					'offset' => $value_offset + $continuation['spacing'][1],
					'length' => \strlen($continuation['spacing'][0]),
					'content' => str_repeat(' ', $indent + $line_indent - $min_indent),
				];
			}
		}

		// Apply replacements backwards to preserve the original offsets.
		for ($i = \count($replacements) - 1; $i >= 0; --$i) {
			$replacement = $replacements[$i];

			$content = substr_replace(
				$content,
				$replacement['content'],
				$replacement['offset'],
				$replacement['length'],
			);
		}

		return $content;
	}
}
